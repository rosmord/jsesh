	/**
	 * Returns all the codes for a given family of signs.
	 * 
	 * @param family
	 * @return
	 */
	public String[] getCodesForFamily(String family) {
		ArrayList l = new ArrayList();
		Iterator it = getCodesSet().iterator();
		while (it.hasNext()) {
			String c = (String) it.next();
			if (c.matches(family + "[0-9]+.*")) {
				l.add(c);
			}
		}
		Collections.sort(l, getCodeComparator());
		return (String[]) l.toArray(new String[l.size()]);
	}

	/**
	 * Returns a comparator able to compare two gardiner codes and to order
	 * them.
	 * 
	 * @return
	 */
	private Comparator getCodeComparator() {
		return new Comparator() {

			Pattern p = Pattern.compile("([A-Za-z]+)([0-9]+)(.*)");

			/*
			 * (non-Javadoc)
			 * 
			 * @see java.util.Comparator#compare(java.lang.Object,
			 *      java.lang.Object)
			 */
			public int compare(Object o1, Object o2) {
				String c1 = (String) o1;
				String c2 = (String) o2;

				Matcher m1 = p.matcher(c1);
				m1.matches();
				String fam1 = m1.group(1);
				int num1 = Integer.parseInt(m1.group(2));
				String tail1 = m1.group(3);

				Matcher m2 = p.matcher(c2);
				m2.matches();
				String fam2 = m2.group(1);
				int num2 = Integer.parseInt(m2.group(2));
				String tail2 = m2.group(3);

				int result = fam1.compareTo(fam2);
				if (result == 0) {
					result = num1 - num2;
					if (result == 0)
						result = tail1.compareTo(tail2);
				}
				return result;
			}
		};
	}
	
	public void addValue(String gardinerCode, String value) {
		if (! signsValues.containsKey(gardinerCode)) {
			signsValues.put(gardinerCode, new ArrayList());
		}
		if (! possibilitiesLists.containsKey(value)) {
			PossibilitiesList l= new PossibilitiesList(value);
			// Ensure the "official" manuel de codage value comes first.
			if (isKnownCode(value)) {
				// For readability, we want to have the "official" phonetic code available.
				l.add(value);
			}
			possibilitiesLists.put(value, l);
			
		}
		((List)signsValues.get(gardinerCode)).add(value);
		((PossibilitiesList)possibilitiesLists.get(value)).add(gardinerCode);
	}
	
	/**
	 * Returns all possible signs for a given value.
	 * @param phoneticValue
	 * @return a PossibilitiesList, or null if the value corresponds to nothing.
	 */
	public PossibilitiesList getPossibilityFor(String phoneticValue) {
		return (PossibilitiesList) possibilitiesLists.get(phoneticValue);
	}
	
